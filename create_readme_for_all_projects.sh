#!/data/data/com.termux/files/usr/bin/bash

# ============================================================
#  ایجاد README.md و LICENSE.md برای تمام پوشه‌های پروژه
# ============================================================

set -e

cd ~/integrated_system_final

# اطمینان از اینکه در شاخه‌ی main هستیم
git checkout main

# دریافت لیست پوشه‌های پروژه (به جز پوشه‌های سیستمی)
projects=$(ls -d */ 2>/dev/null | sed 's|/||g' | grep -v -E '^(node_modules|.git|data|models|frontend|backend|ai-project-manager-light)$')

for project in $projects; do
    echo "=========================================="
    echo "📁 پردازش پروژه: $project"

    # ورود به پوشه‌ی پروژه
    cd "$project" || continue

    # ---------- ایجاد LICENSE.md ----------
    cat > LICENSE.md << 'EOF'
# مجوز MIT

حقوق کپی‌رایت (c) 2026 [نام شما یا سازمان]

با این مجوز، به هر شخصی که نسخه‌ای از این نرم‌افزار و فایل‌های مستندات مرتبط (مجموعاً "نرم‌افزار") را دریافت کند، اجازه داده می‌شود که بدون هزینه و بدون محدودیت، از نرم‌افزار استفاده، کپی، تغییر، ادغام، انتشار، توزیع، زیرمجوز و/یا فروش نسخه‌هایی از نرم‌افزار استفاده کند، مشروط به شرایط زیر:

- در تمام نسخه‌ها یا بخش‌های مهم نرم‌افزار، اطلاعیه‌ی کپی‌رایت فوق و این مجوز درج شود.

این نرم‌افزار "همان‌گونه که هست" و بدون هرگونه ضمانت، اعم از صریح یا ضمنی، از جمله اما نه محدود به ضمانت‌های قابلیت فروش، تناسب برای یک هدف خاص و عدم نقض حقوق دیگران ارائه می‌شود. در هیچ حالتی نویسندگان یا دارندگان کپی‌رایت مسئول هیچگونه ادعا، خسارت یا سایر مسئولیت‌ها، چه در یک اقدام قراردادی، چه در یک اقدام قانونی یا غیره، ناشی از، ناشی از یا مرتبط با نرم‌افزار یا استفاده یا سایر معاملات در نرم‌افزار نخواهند بود.
EOF

    # ---------- ایجاد README.md متناسب با نوع پروژه ----------
    case "$project" in
        *3d*|*3D*|*conversion*|*convert*)
            cat > README.md << 'EOF'
# 🎨 پروژه‌ی تبدیل 2D به 3D

## 🧠 تئوری و معماری
این پروژه یک سرویس **تبدیل تصاویر دو بعدی به مدل‌های سه‌بعدی** است که از الگوریتم‌های پردازش تصویر و شبکه‌های عصبی برای استخراج عمق و بازسازی ساختار سه‌بعدی استفاده می‌کند. معماری آن شامل یک **فرانت‌اند** برای آپلود تصویر و نمایش نتیجه، و یک **بک‌اند** (در صورت وجود) برای پردازش می‌باشد.

## 🏆 دستاوردها
- تبدیل خودکار تصاویر 2D به مدل‌های 3D با کیفیت بالا
- ارائه‌ی پلن‌های مختلف (استاندارد، پریمیوم، اکسپرس) برای کاربران
- رابط کاربری ساده و جذاب برای آپلود و پیش‌نمایش

## 🧩 مشکلات حل‌شده
- بهبود سرعت پردازش با بهینه‌سازی الگوریتم‌ها
- رفع باگ‌های نمایش مدل‌های سه‌بعدی در مرورگرهای مختلف

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **فرانت‌اند**: HTML/CSS/JS با قابلیت drag-and-drop
- **پردازش**: (در صورت وجود) Python/Node.js
- **ذخیره‌سازی**: محلی یا ابری (بسته به پیاده‌سازی)

## 🔧 مهندسی نرم‌افزار
- استفاده از **API** برای ارتباط با سرویس‌های پردازش
- رعایت اصول **کاربری‌محوری** (UX/UI)

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system) مراجعه کنید.
EOF
            ;;

        *nlp*|*NLP*|*text*|*language*)
            cat > README.md << 'EOF'
# 🧠 پروژه‌ی پردازش زبان طبیعی (NLP)

## 🧠 تئوری و معماری
این پروژه شامل مجموعه‌ای از ابزارها و مدل‌های **پردازش زبان طبیعی** برای تحلیل متن، دسته‌بندی، خلاصه‌سازی و پاسخ‌گویی هوشمند است. معماری آن بر پایه‌ی **مدل‌های Transformer** و **کتابخانه‌های متن‌باز** مانند Hugging Face یا spaCy بنا شده است.

## 🏆 دستاوردها
- تحلیل احساسات و دسته‌بندی متون فارسی
- خلاصه‌سازی خودکار متون طولانی
- پاسخ‌گویی به سوالات بر اساس متن ورودی

## 🧩 مشکلات حل‌شده
- بهبود دقت مدل‌ها با داده‌های آموزشی بیشتر
- کاهش زمان پردازش با بهینه‌سازی کد

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **مدل‌ها**: استفاده از پیش‌آموزش‌دیده‌های BERT یا GPT
- **API**: Flask/FastAPI برای ارائه‌ی سرویس
- **فرانت‌اند**: رابط کاربری برای ورودی متن و نمایش خروجی

## 🔧 مهندسی نرم‌افزار
- استفاده از **Docker** برای ایزوله‌سازی محیط
- رعایت اصول **Clean Code**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system) مراجعه کنید.
EOF
            ;;

        *chess*|*Chess*|*shah*)
            cat > README.md << 'EOF'
# ♟️ پروژه‌ی شطرنج (Chess Engine)

## 🧠 تئوری و معماری
این پروژه یک **موتور شطرنج** با قابلیت‌های تحلیل وضعیت، پیش‌بینی حرکات و بازی با هوش مصنوعی است. معماری آن شامل یک **موتور محاسباتی** (بر اساس الگوریتم Minimax و Pruning) و یک **رابط کاربری** برای نمایش صفحه‌ی شطرنج می‌باشد.

## 🏆 دستاوردها
- پیاده‌سازی کامل قوانین شطرنج
- هوش مصنوعی با سطوح مختلف دشواری
- نمایش سه‌بعدی صفحه‌ی شطرنج (در نسخه‌های پیشرفته)

## 🧩 مشکلات حل‌شده
- بهینه‌سازی جستجوی درخت حرکت برای کاهش زمان محاسبه
- رفع باگ‌های مربوط به حرکت‌های خاص (قلعه، آن‌پاسان)

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **موتور**: C++/Python با الگوریتم Minimax
- **فرانت‌اند**: HTML/CSS/JS یا React
- **ارتباط**: WebSocket برای بازی همزمان

## 🔧 مهندسی نرم‌افزار
- استفاده از **TDD** (Test-Driven Development)
- رعایت اصول **SOLID**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system) مراجعه کنید.
EOF
            ;;

        *admin*|*dashboard*|*panel*)
            cat > README.md << 'EOF'
# 📊 داشبورد مدیریتی (Admin Dashboard)

## 🧠 تئوری و معماری
این پروژه یک **داشبورد مدیریتی** برای نظارت بر عملکرد سیستم، مدیریت کاربران و تحلیل داده‌ها است. معماری آن بر پایه‌ی **مؤلفه‌های مجزا** (Widgets) و **اتصال به API** برای دریافت داده‌های لحظه‌ای طراحی شده است.

## 🏆 دستاوردها
- نمایش آمار و نمودارهای تحلیلی
- مدیریت کاربران و نقش‌ها
- پنل پیگیری وضعیت سرویس‌ها

## 🧩 مشکلات حل‌شده
- بهینه‌سازی بارگذاری داده‌های حجیم
- پیاده‌سازی فیلترهای پیشرفته برای جستجو

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **فرانت‌اند**: React/Vue با کتابخانه‌های نمودار (Chart.js)
- **بک‌اند**: Node.js/Python با پایگاه داده
- **اتصال**: RESTful API

## 🔧 مهندسی نرم‌افزار
- استفاده از **Redux** یا **Context API** برای مدیریت حالت
- رعایت اصول **Single Responsibility**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system) مراجعه کنید.
EOF
            ;;

        *)
            # README عمومی برای پروژه‌های دیگر
            cat > README.md << 'EOF'
# 📂 پروژه‌ی `$project`

## 🧠 تئوری و معماری
این پروژه بخشی از مجموعه‌ی یکپارچه‌ی پروژه‌ها است که با هدف [توضیح هدف پروژه] توسعه یافته است. معماری آن بر اساس نیازمندی‌های خاص پروژه طراحی شده و از ماژول‌های مستقل تشکیل شده است.

## 🏆 دستاوردها
- [دستاورد ۱]
- [دستاورد ۲]
- [دستاورد ۳]

## 🧩 مشکلات حل‌شده
- [مشکل ۱]
- [مشکل ۲]

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **زبان‌ها و فریم‌ورک‌ها**: [لیست]
- **پایگاه داده**: [در صورت وجود]
- **رابط کاربری**: [توضیح]

## 🔧 مهندسی نرم‌افزار
- استفاده از [ابزارها و روش‌ها]

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system) مراجعه کنید.
EOF
            ;;
    esac

    # بازگشت به پوشه‌ی اصلی
    cd ..

    # اضافه کردن فایل‌ها و commit
    git add "$project/README.md" "$project/LICENSE.md"
    git commit -m "docs: افزودن README و LICENSE برای پروژه‌ی $project" || echo "⚠️ هیچ تغییری برای commit وجود ندارد."

    echo "✅ پروژه‌ی $project به‌روزرسانی شد."
    echo ""
done

# ارسال همه‌ی تغییرات به GitHub
git push origin main --force

echo "=========================================="
echo "🎯 همه‌ی پروژه‌ها با موفقیت پردازش شدند."
