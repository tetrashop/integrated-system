#!/data/data/com.termux/files/usr/bin/bash

# ============================================================
#  ایجاد README و LICENSE برای تمام سرویس‌های پلتفرم
# ============================================================

set -e

cd ~/integrated_system_final

# اطمینان از اینکه در شاخه‌ی integrated-platform هستیم
git checkout integrated-platform

SERVICES_DIR="integrated-platform/services"

if [ ! -d "$SERVICES_DIR" ]; then
    echo "⚠️ پوشه‌ی services یافت نشد!"
    exit 1
fi

cd "$SERVICES_DIR"

# دریافت لیست سرویس‌ها (پوشه‌های داخل services)
services=$(ls -d */ 2>/dev/null | sed 's|/||g')

for service in $services; do
    echo "=========================================="
    echo "📁 پردازش سرویس: $service"

    if [ ! -d "$service" ]; then
        echo "⚠️ پوشه‌ی $service وجود ندارد، رد می‌شود."
        continue
    fi

    cd "$service" || continue

    # بررسی وجود فایل README
    if [ -f "README.md" ]; then
        echo "✅ README.md از قبل وجود دارد، رد می‌شود."
        cd ..
        continue
    fi

    # ---------- ایجاد LICENSE.md ----------
    cat > LICENSE.md << 'EOF'
# مجوز MIT

حقوق کپی‌رایت (c) 2026 [نام شما یا سازمان]

با این مجوز، به هر شخصی که نسخه‌ای از این نرم‌افزار و فایل‌های مستندات مرتبط (مجموعاً "نرم‌افزار") را دریافت کند، اجازه داده می‌شود که بدون هزینه و بدون محدودیت، از نرم‌افزار استفاده، کپی، تغییر، ادغام، انتشار، توزیع، زیرمجوز و/یا فروش نسخه‌هایی از نرم‌افزار استفاده کند، مشروط به شرایط زیر:

- در تمام نسخه‌ها یا بخش‌های مهم نرم‌افزار، اطلاعیه‌ی کپی‌رایت فوق و این مجوز درج شود.

این نرم‌افزار "همان‌گونه که هست" و بدون هرگونه ضمانت، اعم از صریح یا ضمنی، از جمله اما نه محدود به ضمانت‌های قابلیت فروش، تناسب برای یک هدف خاص و عدم نقض حقوق دیگران ارائه می‌شود. در هیچ حالتی نویسندگان یا دارندگان کپی‌رایت مسئول هیچگونه ادعا، خسارت یا سایر مسئولیت‌ها، چه در یک اقدام قراردادی، چه در یک اقدام قانونی یا غیره، ناشی از، ناشی از یا مرتبط با نرم‌افزار یا استفاده یا سایر معاملات در نرم‌افزار نخواهند بود.
EOF

    # ---------- ایجاد README.md متناسب با نوع سرویس ----------
    case "$service" in
        *3d*|*conversion*)
            cat > README.md << 'EOF'
# 🎨 سرویس تبدیل 2D به 3D

## 🧠 تئوری و معماری
این سرویس **تبدیل تصاویر دو بعدی به مدل‌های سه‌بعدی** را با استفاده از الگوریتم‌های پردازش تصویر ارائه می‌دهد. معماری آن شامل یک API برای دریافت تصویر و خروجی مدل سه‌بعدی است.

## 🏆 دستاوردها
- تبدیل خودکار تصاویر به مدل‌های 3D
- پشتیبانی از فرمت‌های مختلف خروجی (OBJ, STL, GLTF)
- رابط کاربری ساده و جذاب

## 🧩 مشکلات حل‌شده
- بهبود کیفیت خروجی با بهینه‌سازی الگوریتم‌ها
- کاهش زمان پردازش

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **فرانت‌اند**: HTML/CSS/JS با drag-and-drop
- **بک‌اند**: Python/Flask یا Node.js
- **ذخیره‌سازی**: موقت و ابری

## 🔧 مهندسی نرم‌افزار
- استفاده از **RESTful API** برای ارتباط
- رعایت اصول **کاربری‌محوری**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system/tree/integrated-platform) مراجعه کنید.
EOF
            ;;

        *nlp*)
            cat > README.md << 'EOF'
# 🧠 سرویس پردازش زبان طبیعی (NLP)

## 🧠 تئوری و معماری
این سرویس **پردازش زبان طبیعی** را برای تحلیل متن، خلاصه‌سازی و پاسخ‌گویی ارائه می‌دهد. معماری آن بر پایه‌ی مدل‌های Transformer و کتابخانه‌های متن‌باز است.

## 🏆 دستاوردها
- تحلیل احساسات و دسته‌بندی متون
- خلاصه‌سازی خودکار
- پاسخ‌گویی به سوالات

## 🧩 مشکلات حل‌شده
- بهبود دقت مدل‌ها
- کاهش زمان پردازش

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **مدل‌ها**: BERT/GPT
- **API**: Flask/FastAPI
- **فرانت‌اند**: رابط کاربری متنی

## 🔧 مهندسی نرم‌افزار
- استفاده از **Docker** برای ایزوله‌سازی
- رعایت اصول **Clean Code**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system/tree/integrated-platform) مراجعه کنید.
EOF
            ;;

        *shop*|*dashboard*|*admin*)
            cat > README.md << 'EOF'
# 🛍️ سرویس فروشگاه و داشبورد

## 🧠 تئوری و معماری
این سرویس **مدیریت فروشگاه آنلاین** و **داشبورد مدیریتی** را ارائه می‌دهد. معماری آن بر پایه‌ی مؤلفه‌های مجزا و اتصال به API طراحی شده است.

## 🏆 دستاوردها
- مدیریت محصولات، سفارشات و کاربران
- نمایش آمار و نمودارها
- سیستم پرداخت یکپارچه

## 🧩 مشکلات حل‌شده
- بهینه‌سازی بارگذاری داده‌ها
- پیاده‌سازی فیلترهای پیشرفته

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **فرانت‌اند**: React/Vue با Chart.js
- **بک‌اند**: Node.js/Python
- **پایگاه داده**: PostgreSQL/MongoDB

## 🔧 مهندسی نرم‌افزار
- استفاده از **Redux** یا **Context API**
- رعایت اصول **Single Responsibility**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system/tree/integrated-platform) مراجعه کنید.
EOF
            ;;

        *chess*|*olympic*)
            cat > README.md << 'EOF'
# ♟️ سرویس بازی‌های هوشمند

## 🧠 تئوری و معماری
این سرویس **بازی‌های تعاملی** (شطرنج و المپیک) را با قابلیت‌های هوش مصنوعی ارائه می‌دهد. معماری آن بر پایه‌ی موتور بازی و رابط کاربری جذاب طراحی شده است.

## 🏆 دستاوردها
- پیاده‌سازی کامل قوانین بازی
- هوش مصنوعی با سطوح مختلف دشواری
- نمایش تعاملی و جذاب

## 🧩 مشکلات حل‌شده
- بهینه‌سازی عملکرد بازی
- رفع باگ‌های تعاملات کاربر

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **فرانت‌اند**: HTML/CSS/JS با Canvas
- **بک‌اند**: (در صورت وجود) برای مدیریت امتیازات
- **ذخیره‌سازی**: LocalStorage یا پایگاه داده

## 🔧 مهندسی نرم‌افزار
- استفاده از **Game Loop**
- رعایت اصول **UI/UX**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system/tree/integrated-platform) مراجعه کنید.
EOF
            ;;

        *probability*)
            cat > README.md << 'EOF'
# 📊 سرویس ابزارهای احتمالات

## 🧠 تئوری و معماری
این سرویس **ابزارهای محاسباتی و تحلیلی** برای حل مسائل احتمالاتی و آماری ارائه می‌دهد. معماری آن بر پایه‌ی توابع ریاضی و رابط کاربری تعاملی است.

## 🏆 دستاوردها
- محاسبه‌ی احتمالات پیچیده
- نمایش نمودارهای توزیع احتمالات
- ارائه‌ی توضیحات آموزشی

## 🧩 مشکلات حل‌شده
- بهبود دقت محاسبات
- پیاده‌سازی رابط کاربری ساده

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **فرانت‌اند**: HTML/CSS/JS
- **موتور محاسباتی**: JavaScript/Python

## 🔧 مهندسی نرم‌افزار
- استفاده از **TDD** برای تست توابع
- رعایت اصول **KISS**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system/tree/integrated-platform) مراجعه کنید.
EOF
            ;;

        *ai*|*manager*)
            cat > README.md << 'EOF'
# 🤖 سرویس مدیریت پروژه با هوش مصنوعی

## 🧠 تئوری و معماری
این سرویس **مدیریت پروژه‌ها** را با قابلیت‌های پیش‌بینی و اولویت‌بندی خودکار ارائه می‌دهد. معماری آن بر پایه‌ی الگوریتم‌های یادگیری ماشین و API طراحی شده است.

## 🏆 دستاوردها
- پیش‌بینی زمان اتمام پروژه‌ها
- اولویت‌بندی خودکار
- نمایش نمودارهای تحلیلی

## 🧩 مشکلات حل‌شده
- کاهش وابستگی‌های سنگین
- بهبود دقت پیش‌بینی‌ها

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **بک‌اند**: Flask/Python
- **فرانت‌اند**: HTML/CSS/JS با Chart.js
- **ذخیره‌سازی**: فایل JSON

## 🔧 مهندسی نرم‌افزار
- استفاده از **RESTful API**
- رعایت اصول **ماژولاریتی**

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system/tree/integrated-platform) مراجعه کنید.
EOF
            ;;

        *)
            # README عمومی برای سایر سرویس‌ها
            cat > README.md << EOF
# 📂 سرویس \`$service\`

## 🧠 تئوری و معماری
این سرویس بخشی از پلتفرم یکپارچه است که هدف آن **[$service]** می‌باشد. معماری آن بر اساس نیازمندی‌های خاص سرویس طراحی شده است.

## 🏆 دستاوردها
- [دستاورد ۱]
- [دستاورد ۲]
- [دستاورد ۳]

## 🧩 مشکلات حل‌شده
- [مشکل ۱]
- [مشکل ۲]

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **زبان‌ها و فریم‌ورک‌ها**: [لیست]
- **پایگاه داده**: [در صورت وجود]
- **رابط کاربری**: [توضیح]

## 🔧 مهندسی نرم‌افزار
- استفاده از [ابزارها و روش‌ها]

## 📚 مستندات بیشتر
برای اطلاعات بیشتر به [مخزن اصلی](https://github.com/tetrashop/integrated-system/tree/integrated-platform) مراجعه کنید.
EOF
            ;;
    esac

    cd ..

    # اضافه کردن فایل‌ها و commit
    git add "$service/README.md" "$service/LICENSE.md"
    git commit -m "docs: افزودن README و LICENSE برای سرویس‌ی $service" || echo "⚠️ هیچ تغییری برای commit وجود ندارد."

    echo "✅ سرویس‌ی $service به‌روزرسانی شد."
    echo ""
done

# ارسال همه‌ی تغییرات به GitHub
git push origin integrated-platform --force

echo "=========================================="
echo "🎯 همه‌ی سرویس‌های پلتفرم با موفقیت پردازش شدند."
