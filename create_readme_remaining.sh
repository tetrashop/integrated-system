## 🧠 تئوری و معماری
این پروژه یک **پلتفرم فروشگاهی** با قابلیت‌های مدیریت محصولات، سبد خرید، پرداخت و مدیریت کاربران است. معماری آن بر پایه‌ی **میکروسرویس‌ها** یا **ماژول‌های مستقل** طراحی شده و از **API** برای ارتباط بین بخش‌ها استفاده می‌کند.

## 🏆 دستاوردها
- مدیریت کامل محصولات و دسته‌بندی‌ها
- سیستم پرداخت یکپارچه (زرین‌پال، رمزارز)
- داشبورد مدیریتی برای نظارت بر فروش و کاربران
- رابط کاربری واکنش‌گرا (Responsive)

## 🧩 مشکلات حل‌شده
- بهینه‌سازی سرعت بارگذاری صفحات
- پیاده‌سازی سیستم احراز هویت امن
- رفع باگ‌های مربوط به پرداخت و سبد خرید

