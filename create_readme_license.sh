#!/data/data/com.termux/files/usr/bin/bash

# ============================================================
#  ایجاد README.md و LICENSE.md برای تمام شاخه‌های محلی
# ============================================================

set -e  # در صورت بروز خطا متوقف شود

cd ~/integrated_system_final

# دریافت لیست شاخه‌های محلی (به جز HEAD و شاخه‌های remote)
branches=$(git branch --format='%(refname:short)')

for branch in $branches; do
    echo "=========================================="
    echo "🔹 پردازش شاخه: $branch"
    git checkout "$branch"

    # ---------- ایجاد LICENSE.md ----------
    cat > LICENSE.md << 'EOF'
# مجوز MIT

حقوق کپی‌رایت (c) 2026 [نام شما یا سازمان]

با این مجوز، به هر شخصی که نسخه‌ای از این نرم‌افزار و فایل‌های مستندات مرتبط (مجموعاً "نرم‌افزار") را دریافت کند، اجازه داده می‌شود که بدون هزینه و بدون محدودیت، از نرم‌افزار استفاده، کپی، تغییر، ادغام، انتشار، توزیع، زیرمجوز و/یا فروش نسخه‌هایی از نرم‌افزار استفاده کند، مشروط به شرایط زیر:

- در تمام نسخه‌ها یا بخش‌های مهم نرم‌افزار، اطلاعیه‌ی کپی‌رایت فوق و این مجوز درج شود.

این نرم‌افزار "همان‌گونه که هست" و بدون هرگونه ضمانت، اعم از صریح یا ضمنی، از جمله اما نه محدود به ضمانت‌های قابلیت فروش، تناسب برای یک هدف خاص و عدم نقض حقوق دیگران ارائه می‌شود. در هیچ حالتی نویسندگان یا دارندگان کپی‌رایت مسئول هیچگونه ادعا، خسارت یا سایر مسئولیت‌ها، چه در یک اقدام قراردادی، چه در یک اقدام قانونی یا غیره، ناشی از، ناشی از یا مرتبط با نرم‌افزار یا استفاده یا سایر معاملات در نرم‌افزار نخواهند بود.
EOF

    # ---------- ایجاد README.md (متناسب با شاخه) ----------
    case "$branch" in
        "main")
            cat > README.md << 'EOF'
# 📦 سیستم یکپارچه‌ی پروژه‌ها (Integrated Dashboard)

## 🧠 تئوری و معماری
این پروژه یک **داشبورد یکپارچه** است که تمام پروژه‌های موجود در مخزن را به‌صورت یک صفحه‌ی واحد نمایش می‌دهد. معماری آن بر پایه‌ی **نمایش استاتیک** (HTML/CSS/JS) بنا شده و از طریق فایل `projects.json` لیست پروژه‌ها را مدیریت می‌کند. هدف اصلی، ارائه‌ی یک نمای کلی از همه‌ی زیرپروژه‌ها با قابلیت دسترسی سریع به هر یک از آنهاست.

## 🏆 دستاوردها
- یکپارچه‌سازی بیش از ۴۸ پروژه در یک صفحه
- استفاده از طراحی واکنش‌گرا (Responsive) برای نمایش در تمام دستگاه‌ها
- لینک‌دهی مستقیم به `index.html` هر پروژه
- قابلیت به‌روزرسانی خودکار لیست پروژه‌ها با اسکریپت‌های Bash

## 🧩 مشکلات حل‌شده
- **مشکل ۴۰۴ در صفحه اصلی**: با قرار دادن `index.html` جدید در ریشه و غیرفعال کردن کش Vercel برطرف شد.
- **عدم نمایش پروژه‌ها**: با تولید `projects.json` پویا و استفاده از لیست مستقیم در جاوااسکریپت حل شد.
- **خطاهای `git push`**: با تنظیم بافر و استفاده از SSH رفع گردید.

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **لایه‌ی نمایش**: `index.html` و `style.css` و `script.js`
- **لایه‌ی داده**: `projects.json` (تولید شده توسط اسکریپت)
- **لایه‌ی استقرار**: Vercel (با تنظیمات `vercel.json`)

## 🔧 مهندسی نرم‌افزار
- استفاده از **Git** برای کنترل نسخه
- استقرار خودکار روی **Vercel** با هر commit به شاخه‌ی `main`
- رعایت اصول **جداسازی نگرانی‌ها** (Separation of Concerns) با تفکیک کد، محتوا و تنظیمات

## 📚 مستندات بیشتر
برای اطلاعات بیشتر، به [مخزن GitHub](https://github.com/tetrashop/integrated-system) مراجعه کنید.
EOF
            ;;

        "ai-project-manager-light"|"project-intelligence-hub")
            cat > README.md << 'EOF'
# 🧠 مدیریت هوشمند پروژه‌ها با هوش مصنوعی (AI Project Manager)

## 🧠 تئوری و معماری
این پروژه یک **سیستم مدیریت پروژه** با قابلیت‌های **پیش‌بینی هوشمند** و **اولویت‌بندی خودکار** است. معماری آن شامل یک **بک‌اند Flask** (ارائه‌دهنده‌ی API) و یک **فرانت‌اند React/HTML** (نمایش داده‌ها و نمودارها) می‌شود. الگوریتم‌های پیش‌بینی بر اساس **پیشرفت پروژه** و **زمان باقی‌مانده تا ددلاین** طراحی شده‌اند.

## 🏆 دستاوردها
- پیش‌بینی زمان اتمام پروژه‌ها بر اساس داده‌های موجود
- پیشنهاد اولویت (بالا، متوسط، پایین) به‌صورت خودکار
- نمایش نمودارهای تحلیلی (دایره‌ای و میله‌ای) از وضعیت و اولویت پروژه‌ها
- امکان افزودن، ویرایش و حذف پروژه‌ها از طریق رابط کاربری

## 🧩 مشکلات حل‌شده
- **وابستگی‌های سنگین**: با حذف `pandas` و `scikit-learn` و استفاده از `random` ساده، نصب در Termux بدون خطا انجام شد.
- **خطای نصب `numpy`**: با نصب از مخزن Termux (`pkg install python-numpy`) رفع گردید.
- **اتصال بک‌اند و فرانت‌اند**: با تنظیم CORS و پورت‌های متفاوت حل شد.

## 🏗️ معماری و منطق مدار نرم‌افزاری
- **بک‌اند**: Flask (Python) – مدیریت داده‌ها و پردازش‌های هوشمند
- **فرانت‌اند**: HTML/CSS/JS با Chart.js برای نمودارها
- **ذخیره‌سازی**: فایل JSON (برای سادگی و عدم نیاز به دیتابیس)
- **استقرار**: قابلیت اجرا در محیط محلی یا Vercel (با تغییرات جزئی)

## 🔧 مهندسی نرم‌افزار
- استفاده از **API RESTful** برای ارتباط بین لایه‌ها
- رعایت اصول **ماژولاریتی** (جداسازی توابع پیش‌بینی و مدیریت داده)
- استفاده از **کنترل نسخه** با Git و **شاخه‌بندی** مناسب

## 📚 مستندات بیشتر
برای اطلاعات بیشتر، به [مخزن GitHub](https://github.com/tetrashop/integrated-system/tree/ai-project-manager-light) مراجعه کنید.
EOF
            ;;

        *)
            # برای سایر شاخه‌ها یک README عمومی
            cat > README.md << 'EOF'
# 📂 پروژه‌ی عمومی

این شاخه شامل کدهای مرتبط با پروژه‌ی `$branch` است. برای اطلاعات بیشتر به مستندات اصلی مراجعه کنید.

## معماری
این شاخه به‌عنوان بخشی از سیستم یکپارچه‌ی پروژه‌ها توسعه یافته و از معماری مشابه با سایر بخش‌ها پیروی می‌کند.

## دستاوردها
- هماهنگی با سایر پروژه‌های مخزن
- استفاده از استانداردهای کدنویسی مشترک

## مشکلات حل‌شده
- ادغام با داشبورد اصلی
- رفع وابستگی‌ها

## مهندسی نرم‌افزار
رعایت اصول SOLID و استفاده از Git Flow.
EOF
            ;;
    esac

    # اضافه کردن فایل‌ها و commit
    git add README.md LICENSE.md
    git commit -m "docs: افزودن README و LICENSE برای شاخه‌ی $branch" || echo "⚠️ هیچ تغییری برای commit وجود ندارد."
    git push -u origin "$branch" --force

    echo "✅ شاخه‌ی $branch به‌روزرسانی شد."
    echo ""
done

git checkout main  # بازگشت به شاخه‌ی اصلی
echo "=========================================="
echo "🎯 همه‌ی شاخه‌ها با موفقیت پردازش شدند."
